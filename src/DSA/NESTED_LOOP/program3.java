package DSA.NESTED_LOOP;

public class program3 {
    public static void main(String[] args) {
        int n = 4;
        for (int i = 0; i <= n ; i++) {

            for (int k = 0; k < 4-i ; k++) {
                System.out.print(" ");
            }

            for (int j = -1; j < i ; j++) {
                System.out.print("* ");

            }

            System.out.print("\n");




        }

//            System.out.print("\n");


        }
    }


